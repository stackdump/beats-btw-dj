import { readFileSync } from 'node:fs';
const rows = JSON.parse(readFileSync('symbolic.json')).filter(r=>!r.error);
const m = a => a.reduce((x,y)=>x+y,0)/a.length;
const q = (a,p)=>{const s=[...a].sort((x,y)=>x-y);return s[Math.floor(p*(s.length-1))];};
const f = (name, a) => console.log(name.padEnd(28), 'mean', m(a).toFixed(2), 'min', Math.min(...a).toFixed(2), 'median', q(a,.5).toFixed(2), 'max', Math.max(...a).toFixed(2));
console.log('tracks', rows.length);
f('song seconds', rows.map(r=>r.seconds)); f('bars', rows.map(r=>r.bars));
f('late max ticks', rows.map(r=>r.latenessMax)); f('late mean', rows.map(r=>r.latenessMean));
f('density contrast', rows.map(r=>r.densContrast));
f('mix distinct bars / bars', rows.map(r=>r.repetition.mix.distinct/r.repetition.mix.bars));
f('drum distinct bars', rows.map(r=>r.repetition.drums.distinct));
f('melody distinct bars', rows.map(r=>r.repetition.melody.distinct));
f('melody bars', rows.map(r=>r.repetition.melody.bars));
f('deflate ratio', rows.map(r=>r.repetition.deflateRatio));
f('mel rep', rows.map(r=>r.melody.intervals.rep)); f('mel step', rows.map(r=>r.melody.intervals.step)); f('mel skip', rows.map(r=>r.melody.intervals.skip)); f('mel leap', rows.map(r=>r.melody.intervals.leap));
f('mel range', rows.map(r=>r.melody.range)); f('mel onbeat', rows.map(r=>r.melody.onBeatShare));
f('chords/song', rows.map(r=>r.harmony.chordsPerSong)); f('vl actual', rows.map(r=>r.harmony.vlActual)); f('vl optimal', rows.map(r=>r.harmony.vlOptimal));
f('cons', rows.map(r=>r.harmony.melConsonanceOnBeat));
f('bass distinct', rows.map(r=>r.bass.distinctPitches)); f('bass root', rows.map(r=>r.bass.rootShare));
f('hat vel variants/pos', rows.map(r=>r.hatVelVariantsPerPos));
const vd = rows.flatMap(r=>['kick','snare','hihat'].filter(k=>r.velStats[k]).map(k=>r.velStats[k].distinct)); f('drum distinct velocities', vd);
const vs = rows.flatMap(r=>['melody','bass','harmony'].filter(k=>r.velStats[k]).map(k=>r.velStats[k].distinct)); f('tonal distinct velocities', vs);
console.log('harmony vel distinct', [...new Set(rows.map(r=>r.velStats.harmony?.distinct))]);
console.log('swing>0 genres', rows.filter(r=>r.swing>0).length/3, 'humanize>0', rows.filter(r=>r.humanize>0).length/3);
console.log('phraseBars', [...new Set(rows.flatMap(r=>r.phraseBars))]);
console.log('forms', [...new Set(rows.map(r=>r.form))].slice(0,8));
